# این سه مقدار را جداگانه تغییر بده؛ هر بار فقط یکی را دست‌کاری کن.
a, b, c = 1.0, -2.0, 3.0
# نرخ گام را بزرگ‌تر کن و خروجی تازه را با نسخهٔ اولیه مقایسه کن.
rate = 0.01


def function(x, y, z):
    # همان ساختار جمع و ضربِ مثال منبع: f = a + b*c.
    return x + y * z


# هر مشتق فقط تغییر یک ورودی را با ثابت‌گرفتن دو ورودی دیگر می‌سنجد.
gradient = [1.0, c, b]
# برای نزول، هر پارامتر را در خلاف جهت مشتق خودش تغییر می‌دهیم.
updated = [value - rate * g for value, g in zip([a, b, c], gradient)]
# عددهای دقیق کد را گزارش می‌کنیم؛ گردکردن متن اسلاید در کد تحمیل نشده است.
result = {
    "before": function(a, b, c),
    "gradient": gradient,
    "updated": updated,
    "after": function(*updated),
}
