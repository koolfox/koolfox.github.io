"""کارگاه مستقل نگاشت همانی با یک مسیر باقیماندهٔ خطی؛ مرتبط با صفحهٔ 40.

این مثال اسکالر، معماری کامل ResNet یا آزمایش ImageNet نیست.
"""

# ورودی و هدف برابرند: می‌خواهیم خروجی همان x شود؛ عدد را به 1 یا 3 تغییر بده.
x = 2.0
# تنها وزنِ قابل یادگیریِ مسیر باقیمانده است؛ با صفرشدن آن، خروجی عین ورودی می‌شود.
weight = 0.5
# گام یادگیری را کوچک تغییر بده؛ مقدار بزرگ ممکن است زیان را افزایش دهد.
learning_rate = 0.1
# تعداد به‌روزرسانی‌ها؛ مقدار 4 برای دیدن روند کوتاه کافی است.
steps = 4
# تاریخچه، وضعیت پیش از هر به‌روزرسانی و وضعیت نهایی را نگه می‌دارد.
history = []
for step in range(steps + 1):
    # مسیر قابل یادگیری F(x)=weight*x است؛ مسیر میان‌بُر خود x را اضافه می‌کند.
    residual = weight * x
    prediction = x + residual
    # هدف x است؛ این همان فرم زیان مربعیِ مثال صفحهٔ 40 است.
    loss = (prediction - x) ** 2
    history.append({"step": step, "weight": weight, "prediction": prediction, "loss": loss})
    if step < steps:
        # قاعدهٔ زنجیره: مشتق زیان نسبت به وزن برابر 2*(prediction-x)*x است.
        gradient = 2 * (prediction - x) * x
        # نزول گرادیان، وزن مسیر باقیمانده را به سمت مقدار مناسب حرکت می‌دهد.
        weight -= learning_rate * gradient

# این خروجی امکان مقایسهٔ پیش‌بینی با ورودی و مشاهدهٔ کاهش زیان را می‌دهد.
result = {"input": x, "identity_target": x, "history": history}
