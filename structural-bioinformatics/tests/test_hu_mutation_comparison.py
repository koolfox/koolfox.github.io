"""The Hu 2013 mutation comparison stays reproducible and keeps the full text out of the repo."""

import importlib.util
import json
import math
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    "compare_hu_mutations", PROJECT / "scripts/compare_hu_mutations.py"
)
comparator = importlib.util.module_from_spec(spec)
spec.loader.exec_module(comparator)
RECORD = json.loads((PROJECT / "data/metadata/hu-2013-mutations.json").read_text())
PUBLISHED = json.loads((PROJECT / "data/processed/hu-mutation-comparison.json").read_text())
# The handout is generated by scripts/export_preparation_guide.mjs; no publisher PDF is kept.
ALLOWED_PDFS = {"assets/preparation-guide.fa.pdf"}


def test_published_comparison_is_reproducible():
    assert PUBLISHED == comparator.compare(PROJECT)


def test_every_mutated_residue_is_in_our_contact_map():
    epitope = json.loads((PROJECT / "data/processed/full-epitope.json").read_text())
    mapped = {
        key.split(":", 1)[1]
        for chain in epitope["per_protomer"].values()
        for key in chain["tnf_residues"]
    }
    mutated = {row["residue"] for row in RECORD["table_3"]["rows"] if row["residue"]}
    assert mutated <= mapped
    for row in PUBLISHED["comparison"]:
        assert row["contacting_chain"] in {"A", "C"}
        assert row["our_heavy_atom_contacts"] > 0
    # Six of the fourteen tested residues contact the Fab only through the neighbouring protomer.
    assert PUBLISHED["summary"]["mutants_reached_only_through_the_neighbouring_protomer"] == 6


def test_quoted_q21a_numbers_agree_with_the_executed_analysis():
    epitope = json.loads((PROJECT / "data/processed/full-epitope.json").read_text())
    context = epitope["hu_2013_q21a_context"]
    rows = {row["residue"]: row for row in RECORD["table_3"]["rows"]}
    wild_type = next(row for row in RECORD["table_3"]["rows"] if row["residue"] is None)
    assert context["kd_wild_type_molar"] == wild_type["KD"]
    assert context["kd_q21a_molar"] == rows["GLN21"]["KD"]
    q21a = next(r for r in PUBLISHED["comparison"] if r["residue"] == "GLN21")
    assert round(context["kd_ratio"], 1) == q21a["authors_kd_fold_change_vs_wild_type"]
    assert context["q21_delta_sasa_angstrom2"] == q21a["our_delta_sasa_angstrom2"]


def test_authors_values_stay_labelled_as_theirs():
    # Nothing in the record may present the SPR measurements as this project's own result.
    assert RECORD["provenance"]["user_supplied_pdf"]["committed"] is False
    assert RECORD["authors_reported_interface"]["two_protomer_epitope_reported"] is True
    for row in PUBLISHED["comparison"]:
        assert "authors_kd_fold_change_vs_wild_type" in row
    assert PUBLISHED["limitations"]


def test_pdf_spot_check_agrees_with_the_recorded_table():
    # Two rows were read back from the publisher PDF; the record may not drift away from them.
    rows = {row["label"]: row for row in RECORD["table_3"]["rows"]}
    checked = RECORD["provenance"]["user_supplied_pdf"]["spot_check"]["rows"]
    assert checked
    for entry in checked:
        assert entry["matches_record"] is True
        value, error = entry["pdf_reading"].removesuffix(" M").split(" x 10^")
        mantissa, uncertainty = (float(part) for part in value.split(" +/- "))
        scale = 10.0 ** int(error)
        row = rows[entry["label"]]
        # Decimal mantissas do not round-trip exactly through binary floats.
        assert math.isclose(row[entry["field"]], mantissa * scale, rel_tol=1e-12)
        assert math.isclose(row[f"{entry['field']}_error"], uncertainty * scale, rel_tol=1e-12)


def test_no_publisher_pdf_is_committed():
    found = {
        path.relative_to(PROJECT).as_posix()
        for path in PROJECT.rglob("*.pdf")
        if not {"node_modules", ".venv", "dist"} & set(path.parts)
    }
    assert found <= ALLOWED_PDFS
